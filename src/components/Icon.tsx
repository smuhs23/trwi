export function Icon({
  name,
  size = 20,
  ...props
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const C = icons[name as keyof typeof icons] || Compass;
  return <C size={size} strokeWidth={1.8} aria-hidden="true" {...props} />;
}
